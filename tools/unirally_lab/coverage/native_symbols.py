"""The address-to-native-symbol index (NATIVE-READABILITY).

The native code cites the original's ROM and WRAM addresses in its comments. This
module finds every such citation in ``src/core`` and names the native symbol it
belongs to (the function whose body holds it, the state member or constant it
documents), so "where is ``$81:C238`` in native" stays a lookup after the code is
reorganised by game system. A lookup also lists the research and task records that
cite the address; those links are computed, not tracked, so a records-only change
never makes the index stale.

The output, ``docs/map/static/native-symbols.json``, is tracked and regenerated by
``coverage native-symbols``; ``coverage static-map`` reads it to name the native
symbols beside each routine. It needs no ROM. The scanner is a small C++ scope
reader, not a compiler: it knows namespaces, classes, enums, functions and
brace-initialised data, which is all ``src/core`` uses.

Citation forms (the style rules in ``src/core/README.md``):

- ROM: ``$BB:AAAA`` or ``$BBAAAA``; a range ``$BB:AAAA-AAAA`` or ``$BB:AAAA-$BB:AAAA``;
  more addresses in the same bank without it, ``$80:84CB/84DB`` or ``$83:E611, E663``.
  The code banks' low mirrors ``$00``-``$03`` are normalised to ``$80``-``$83``.
- WRAM: ``$AAAA`` below ``$2000`` (the low-WRAM mirror every bank sees), or
  ``$7E:AAAA``/``$7F:AAAA``; ``$7E:0000``-``$7E:1FFF`` is keyed as ``$0000``-``$1FFF``;
  a range ``$114D-$119C``. SRAM is ``$70``-``$77``.
- ``io``: a bank-less ``$2000``-``$7FFF``, keyed ``$00:AAAA``. That is an I/O register
  (``$4210``) or, in comments older than the rules, a VRAM word or colour written with ``$``.
- ``$`` marks an address. A value written ``$0213`` is read as WRAM ``$0213``, which
  is why the rules ask for values in decimal or ``0x``; ``$8000`` and above without a
  bank is taken as a value and skipped. A C++ form the scanner does not read (a
  requires-clause) raises ``UnsupportedShape`` rather than guess.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable

SOURCES = ("src/core/*.hpp", "src/core/*.cpp")
RECORDS = ("docs/research/*.md", "tasks/*.md", "docs/inventory/*.md", "docs/content/*.md")
OUT = "docs/map/static/native-symbols.json"
REGENERATE = f"python3 tools/project.py coverage native-symbols --out {OUT}"

HEX = "0-9A-Fa-f"
# A long address, colon optional, then an optional range end in the same bank. A
# leading hex digit, ':' or '#' means we are inside another token or an immediate.
LONG = re.compile(rf"(?<![{HEX}:#\w])\$([{HEX}]{{2}}):?([{HEX}]{{4}})(?![{HEX}])"
                  rf"(?:\s*[-–]\s*(?:\$([{HEX}]{{2}}):?)?([{HEX}]{{4}})(?![{HEX}]))?")
# More addresses in the same bank after a long one, written without the bank:
# "$80:84CB/84DB", "$83:E611, E663", "$82:A9C1-A9E0 / AA1E-AA3D".
MORE = re.compile(rf"\s*([/,])\s*([{HEX}]{{4}})(?![{HEX}\w])(?:\s*[-–]\s*([{HEX}]{{4}})(?![{HEX}\w]))?")
# A bank-less address, with an optional range end: "$0C73", "$114D-$119C".
SHORT = re.compile(rf"(?<![{HEX}:#\w$])\$([{HEX}]{{4}})(?![{HEX}])(?:\s*[-–]\s*\$?([{HEX}]{{4}})(?![{HEX}]))?")
REGIONS = ("rom", "wram", "sram", "io")
KEYWORDS = {"if", "for", "while", "switch", "catch", "return", "sizeof", "decltype", "alignas",
            "static_assert", "alignof", "noexcept", "requires"}


# ------------------------------------------------------------------ addresses


def region(bank: int, offset: int) -> str:
    if bank in (0x7E, 0x7F):
        return "wram"
    if 0x70 <= bank <= 0x77 and offset < 0x8000:
        return "sram"
    if offset < 0x8000:
        return "wram" if offset < 0x2000 else "io"
    return "rom"


def key(bank: int | None, offset: int) -> str:
    """The index's spelling of an address. `bank` None is a bank-less (low-page) address."""
    if bank is None or (bank < 0x40 or bank == 0x7E) and offset < 0x2000:
        return f"${offset:04X}"         # low WRAM: $7E:0C73 and $0C73 are the same byte
    if region(bank, offset) == "rom" and bank < 0x04:
        bank |= 0x80                    # the code banks' low mirror
    return f"${bank:02X}:{offset:04X}"


@dataclass(frozen=True)
class Cite:
    region: str          # rom, wram, sram or io
    address: str         # "$81:C238" or "$0C73"
    end: str | None      # the range end in the same form, if cited as a range


def _cite(bank: int | None, offset: int, end: int | None) -> Cite:
    reg = region(0x00 if bank is None else bank, offset)
    last = key(bank, end) if end is not None and end >= offset else None
    return Cite(reg, key(bank, offset), last)


def cites(text: str) -> list[Cite]:
    """Every address a comment cites, in the forms of the module docstring."""
    out: list[Cite] = []
    taken: list[tuple[int, int]] = []
    for m in LONG.finditer(text):
        bank, off = int(m.group(1), 16), int(m.group(2), 16)
        if ":" not in m.group(0)[:4] and not (bank < 0x04 or 0x80 <= bank <= 0x83 or 0x70 <= bank <= 0x7F):
            continue            # $BBAAAA without a colon is only read for code, SRAM and WRAM banks
        end = None
        if m.group(4) and (not m.group(3) or int(m.group(3), 16) == bank):
            end = int(m.group(4), 16)
        out.append(_cite(bank, off, end))
        stop = m.end()
        # Bank-less continuations. A comma continuation must be a code-bank ROM address
        # ($8000 or above), so "$83:CEC9, 1252 updates" does not read 1252 as an address.
        while (more := MORE.match(text, stop)):
            follow = int(more.group(2), 16)
            if more.group(1) == "," and not (region(bank, follow) == "rom" and follow >= 0x8000):
                break
            out.append(_cite(bank, follow, int(more.group(3), 16) if more.group(3) else None))
            stop = more.end()
        taken.append((m.start(), stop))
    for m in SHORT.finditer(text):
        if any(a <= m.start() < b for a, b in taken):
            continue
        off = int(m.group(1), 16)
        if off < 0x8000:        # $8000 and above without a bank is a value, not an address
            out.append(_cite(None if off < 0x2000 else 0x00, off, int(m.group(2), 16) if m.group(2) else None))
    return out


def parse_key(address: str) -> int:
    """Sort key and span arithmetic: "$81:C238" -> 0x81C238, "$0C73" -> 0x0C73."""
    return int(address[1:].replace(":", ""), 16)


# -------------------------------------------------------------------- scanner


def split_code_and_comments(text: str) -> list[tuple[str, str]]:
    """Per line: (code with string/char literals blanked, comment text).

    A line holding an empty comment gets the comment text "\n", so it still reads as a
    comment line and a blank `//` inside a block does not split the block."""
    lines: list[tuple[str, str]] = []
    code: list[str] = []
    note: list[str] = []
    i, n = 0, len(text)
    block = False
    while i < n:
        c = text[i]
        if c == "\n":
            lines.append(("".join(code), "".join(note)))
            code, note = [], []
            if block:
                note.append("\n")
            i += 1
            continue
        if block:
            if not note:
                note.append("\n")
            if text.startswith("*/", i):
                block = False
                i += 2
            else:
                note.append(c)
                i += 1
            continue
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            note.append(text[i + 2:j] or "\n")
            i = j
            continue
        if text.startswith("/*", i):
            block = True
            i += 2
            continue
        if c == "'" and i and text[i - 1].isalnum() and i + 1 < n and text[i + 1].isalnum():
            code.append(c)      # a digit separator (1'000), not a character literal
            i += 1
            continue
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            code.append(c + c)
            i = j + 1
            continue
        code.append(c)
        i += 1
    lines.append(("".join(code), "".join(note)))
    return lines


@dataclass
class Scope:
    kind: str            # namespace, class, function, block (inside a function), init
    name: str            # qualified symbol for class, function and data scopes
    start: int


@dataclass
class Decl:
    start: int
    end: int
    names: list[str]     # qualified symbols this declaration introduces
    opens_scope: bool = False


@dataclass
class FileScan:
    path: str
    decls: list[Decl] = field(default_factory=list)
    # line -> the function or data scope the line lies inside, if any
    inside: dict[int, str] = field(default_factory=dict)
    # lines inside a braced initialiser, whose comments belong to the declaration holding them
    within_declaration: set[int] = field(default_factory=set)
    # line -> the enclosing class, if any (for comments that attach to nothing)
    enclosing_class: dict[int, str] = field(default_factory=dict)


def _strip_template(prefix: str) -> str:
    s = prefix.strip()
    while s.startswith("template"):
        depth, i = 0, len("template")
        while i < len(s):
            if s[i] == "<":
                depth += 1
            elif s[i] == ">":
                depth -= 1
                if depth == 0:
                    i += 1
                    break
            i += 1
        s = s[i:].strip()
    return s


OPERATOR = re.compile(r"\boperator\s*(\(\)|\[\]|[^\s\w(]+|new|delete)\s*\(")


def function_name(prefix: str) -> str | None:
    """The name of the function whose definition `prefix` begins, or None."""
    s = _strip_template(prefix)
    op = OPERATOR.search(s)
    if op:
        # An operator's symbol ("<", "<<", "==", "()") must not count as a bracket or
        # an initialiser; the name is the qualified operator itself.
        head = s[:op.start()]
        if "=" in head.replace("==", "").replace("<=", "").replace(">=", "").replace("!=", ""):
            return None
        m = re.search(r"((?:~?[A-Za-z_]\w*::)*)$", head.rstrip())
        return (m.group(1) if m else "") + "operator" + op.group(1)
    paren = -1
    depth = 0
    for i, c in enumerate(s):
        if c == "<":
            depth += 1
        elif c == ">":
            depth = max(0, depth - 1)
        elif c == "=" and depth == 0:
            return None     # an initialiser, not a definition
        elif c == "(" and depth == 0:
            paren = i
            break
    if paren < 0:
        return None
    m = re.search(r"((?:~?[A-Za-z_]\w*::)*~?[A-Za-z_]\w*)\s*$", s[:paren])
    if not m or m.group(1).split("::")[-1] in KEYWORDS:
        return None
    return m.group(1)


def declared_names(statement: str) -> list[str]:
    """Names a declaration statement at class or namespace scope introduces."""
    s = _strip_template(statement).strip().rstrip(";").strip()
    if not s or s.startswith(("using ", "friend ", "#", "static_assert", "public", "private", "protected")):
        if s.startswith("using ") and "=" in s:
            return [s[len("using "):s.index("=")].strip()]
        return []
    if re.match(r"(struct|class|union|enum)\b[^({=]*$", s):
        m = re.match(r"(?:struct|class|union|enum(?:\s+class|\s+struct)?)\s+(\w+)", s)
        return [m.group(1)] if m else []
    fn = function_name(s)
    if fn:
        return [fn]
    # Drop initialisers and array bounds, then take the last identifier of each declarator.
    flat, depth = [], 0
    for c in s:
        if c in "({[<":
            depth += 1
            continue
        if c in ")}]>":
            depth -= 1
            continue
        if depth == 0:
            flat.append(c)
    parts = "".join(flat).split(",")
    names = []
    for part in parts:
        part = part.split("=")[0]
        ids = re.findall(r"[A-Za-z_]\w*", part)
        ids = [i for i in ids if i not in ("const", "constexpr", "static", "inline", "mutable", "unsigned", "signed")]
        if ids:
            names.append(ids[-1])
    return names


def scan(path: str, text: str) -> tuple[FileScan, list[tuple[str, str]]]:
    lines = split_code_and_comments(text)
    fs = FileScan(path)
    stack: list[Scope] = []
    pending: list[str] = []
    pending_start: int | None = None

    def qualify(name: str) -> str:
        classes = [s.name for s in stack if s.kind == "class"]
        return "::".join(classes[-1:] + [name]) if classes and "::" not in name else name

    def in_code() -> Scope | None:
        for s in reversed(stack):
            if s.kind == "function":
                return s
        return None

    for ln, (code, _) in enumerate(lines, start=1):
        if stack and stack[-1].kind == "init":
            fs.within_declaration.add(ln)
        owner = in_code()
        if owner:
            fs.inside[ln] = owner.name
        cls = next((s.name for s in reversed(stack) if s.kind == "class"), None)
        if cls:
            fs.enclosing_class[ln] = cls
        stripped = code.strip()
        if stripped.startswith("#"):
            continue
        for c in code:
            if stack and stack[-1].kind == "init":
                # A braced initialiser (or a lambda) inside a declaration: its ';' end nothing.
                if c == "{":
                    stack.append(Scope("init", "", ln))
                elif c == "}":
                    stack.pop()
                pending.append(c)
                continue
            if in_code():
                if c == "{":
                    stack.append(Scope("block", in_code().name, ln))
                elif c == "}":
                    closed = stack.pop()
                    if closed.kind == "function":
                        for d in fs.decls:
                            if d.opens_scope and d.names == [closed.name] and d.end == -1:
                                d.end = ln
                        pending, pending_start = [], None
                continue
            if c == "{":
                prefix = "".join(pending)
                start = pending_start if pending_start is not None else ln
                kind, name = classify(prefix)
                if kind == "init":
                    if pending_start is None:
                        pending_start = ln
                    stack.append(Scope("init", "", ln))
                    pending.append("{")
                    continue
                if kind in ("class", "function") and name:
                    name = qualify(name)
                    fs.decls.append(Decl(start, -1, [name], opens_scope=True))
                stack.append(Scope(kind, name, start))
                if kind == "function":
                    for line in range(start, ln + 1):   # a signature wrapped over several lines
                        fs.inside[line] = name
                pending, pending_start = [], None
            elif c == "}":
                closed = stack.pop() if stack else None
                if closed and closed.kind == "class":
                    for d in fs.decls:
                        if d.opens_scope and d.names == [closed.name] and d.end == -1:
                            d.end = ln
                pending, pending_start = [], None
            elif c == ";":
                statement = "".join(pending)
                if statement.strip():
                    names = [qualify(n) for n in declared_names(statement)]
                    if names:
                        fs.decls.append(Decl(pending_start or ln, ln, names))
                pending, pending_start = [], None
            elif c == ":" and "".join(pending).strip() in ("public", "private", "protected"):
                pending, pending_start = [], None     # an access specifier ends no declaration
            else:
                if pending_start is None and not c.isspace():
                    pending_start = ln
                pending.append(c)
        pending.append(" ")
    for d in fs.decls:
        if d.end == -1:
            d.end = len(lines)
    return fs, lines


class UnsupportedShape(ValueError):
    """A C++ form the scanner does not read; refusing beats a wrong attribution."""


def classify(prefix: str) -> tuple[str, str]:
    s = prefix.strip()
    if re.search(r"\brequires\b", s):
        raise UnsupportedShape(f"a requires-clause is not read by the native-symbol scanner: {s[:80]}")
    if re.search(r"\bnamespace\b", s) or s.startswith('extern "'):
        return "namespace", ""
    if not s:
        return "block", ""
    if s.count("(") > s.count(")"):
        return "init", ""       # a braced value inside a parameter list or a call
    head = _strip_template(s)
    m = re.match(r"(?:struct|class|union|enum(?:\s+class|\s+struct)?)\s+(?:\[\[[^\]]*\]\]\s*)?(\w+)[^(=]*$", head)
    if m:
        return "class", m.group(1)
    fn = function_name(s)
    if fn:
        close = s.rfind(")")
        tail = s[close + 1:] if close >= 0 else ""
        if re.search(r"(?<!:):(?!:)", tail) and re.search(r"[\w>]\s*$", s):
            return "init", ""   # a braced member initialiser inside a constructor's init list
        return "function", fn
    return "init", ""           # a braced initialiser: part of the declaration it begins


# ---------------------------------------------------------------- attachment


def attach(fs: FileScan, lines: list[tuple[str, str]]) -> list[tuple[int, str, str]]:
    """(line, symbol, comment) for every comment line."""
    starts: dict[int, Decl] = {}
    for d in fs.decls:
        starts.setdefault(d.start, d)
    out = []
    n = len(lines)
    for ln, (code, note) in enumerate(lines, start=1):
        if not note:
            continue
        symbol = fs.inside.get(ln)
        if symbol is None and code.strip():
            # A trailing comment: the declaration this line belongs to.
            covering = [d for d in fs.decls if d.start <= ln <= d.end and not d.opens_scope] or \
                       [d for d in fs.decls if d.start == ln]
            if covering:
                symbol = ", ".join(covering[-1].names)
        if symbol is None and ln in fs.within_declaration:
            # A comment line inside a braced initialiser (a table entry's note).
            covering = [d for d in fs.decls if d.start <= ln <= d.end and not d.opens_scope]
            if covering:
                symbol = ", ".join(covering[-1].names)
        if symbol is None and not code.strip():
            # A leading comment block: the declaration that starts right after the block.
            j = ln + 1
            while j <= n and lines[j - 1][1] and not lines[j - 1][0].strip():
                j += 1
            if j <= n and lines[j - 1][0].strip() and j in starts:
                symbol = ", ".join(starts[j].names)
        if symbol is None:
            symbol = fs.enclosing_class.get(ln, "(file)")
        out.append((ln, symbol, note))
    return out


# ------------------------------------------------------------------- records


def record_citations(root: Path) -> tuple[dict[str, set[str]], list[tuple[int, int, str]]]:
    """Address -> records citing it, and the ROM ranges records cite (start, end, record)."""
    exact: dict[str, set[str]] = {}
    ranges: list[tuple[int, int, str]] = []
    for g in RECORDS:
        for path in sorted(root.glob(g)):
            rel = path.relative_to(root).as_posix()
            for c in cites(path.read_text(encoding="utf-8")):
                exact.setdefault(c.address, set()).add(rel)
                if c.end and c.region == "rom":
                    ranges.append((parse_key(c.address), parse_key(c.end), rel))
    return exact, ranges


# ---------------------------------------------------------------------- build


def build(root: Path) -> dict[str, Any]:
    """The tracked index. It depends on src/core only, so a records-only change never stales it."""
    entries: dict[str, dict[str, Any]] = {}
    symbols: dict[str, dict[str, set[str]]] = {}
    for g in SOURCES:
        for path in sorted(root.glob(g)):
            rel = path.relative_to(root).as_posix()
            fs, lines = scan(rel, path.read_text(encoding="utf-8"))
            for _, symbol, note in attach(fs, lines):
                for c in cites(note):
                    qualified = f"{rel}:{symbol}"
                    e = entries.setdefault(c.address, {"region": c.region, "ends": set(), "native": set()})
                    e["native"].add(qualified)
                    if c.end:
                        e["ends"].add(c.end)
                    symbols.setdefault(qualified, {}).setdefault(c.region, set()).add(c.address)
    rows = []
    for address, e in sorted(entries.items(), key=lambda kv: (REGIONS.index(kv[1]["region"]), parse_key(kv[0]))):
        row = {"address": address, "region": e["region"], "native": sorted(e["native"])}
        if e["ends"]:
            row["range_ends"] = sorted(e["ends"], key=parse_key)
        rows.append(row)
    return {
        "schema_version": 1,
        "kind": "native_symbol_index",
        "regeneration_command": REGENERATE,
        "note": "Generated from the address citations in src/core comments (NATIVE-READABILITY); do not edit by hand. "
                "`native` names file:symbol: the function whose body holds the citation, or the member, constant, "
                "type or declaration it documents. `coverage native-symbols --lookup <address>` adds the records "
                "citing an address; `coverage static-map` names these symbols beside each routine.",
        "totals": {"addresses": len(rows), **{f"{k}_addresses": sum(1 for r in rows if r["region"] == k) for k in REGIONS},
                   "native_symbols": len(symbols)},
        "addresses": rows,
        "symbols": {s: {r: sorted(v, key=parse_key) for r, v in sorted(regions.items())} for s, regions in sorted(symbols.items())},
    }


def records_for(index: dict[str, Any], root: Path) -> dict[str, list[str]]:
    """Address -> the records citing it; a ROM address also links to a cited range holding it."""
    exact, ranges = record_citations(root)
    out = {}
    for row in index["addresses"]:
        recs = set(exact.get(row["address"], ()))
        if row["region"] == "rom":
            key = parse_key(row["address"])
            recs |= {r for a, b, r in ranges if a <= key <= b}
        out[row["address"]] = sorted(recs)
    return out


def rom_without_record(index: dict[str, Any], root: Path) -> list[str]:
    links = records_for(index, root)
    return [r["address"] for r in index["addresses"] if r["region"] == "rom" and not links[r["address"]]]


def lookup(index: dict[str, Any], root: Path, query: str) -> dict[str, Any]:
    """Native symbols and records for an address (any citation form) or for a symbol substring."""
    found = cites(query)
    links = records_for(index, root)
    if found:
        address = found[0].address
        k = parse_key(address)
        rows = [r for r in index["addresses"] if r["address"] == address]
        rows += [r for r in index["addresses"] if r["region"] == found[0].region and r["address"] != address
                 and parse_key(r["address"]) <= k <= max([parse_key(r["address"])] + [parse_key(e) for e in r.get("range_ends", ())])]
        return {"query": address, "addresses": [{**r, "records": links[r["address"]]} for r in rows]}
    return {"query": query, "symbols": {s: v for s, v in index["symbols"].items() if query in s}}


def dump(doc: Any) -> str:
    return json.dumps(doc, indent=1, sort_keys=True) + "\n"


def native_by_rom_span(index: dict[str, Any]) -> list[tuple[int, int, str]]:
    """(first, last, file:symbol) for every ROM citation, a single address spanning itself."""
    out = []
    for row in index.get("addresses", ()):
        if row["region"] != "rom":
            continue
        first = parse_key(row["address"])
        last = max([first] + [parse_key(e) for e in row.get("range_ends", ())])
        out.extend((first, last, s) for s in row["native"])
    return out


def symbols_in(span: Iterable[tuple[int, int, str]], start: int, end: int) -> list[str]:
    """Native symbols citing any address in [start, end] (24-bit $BBAAAA keys)."""
    return sorted({s for a, b, s in span if a <= end and b >= start})
